package consulo.nodejs.npm;

import consulo.annotation.access.RequiredReadAction;
import consulo.annotation.component.ComponentScope;
import consulo.annotation.component.ExtensionAPI;
import consulo.module.Module;
import consulo.module.content.layer.ModifiableRootModel;
import consulo.virtualFileSystem.VirtualFile;

import java.util.function.Consumer;

/**
 * Configures a module from its {@code package.json}, like the Maven importers: the frameworks the package depends on
 * enable their module extensions ({@link NpmImporterFromDependency}).
 * <p>
 * Called by {@link NpmProjectModel#apply} - on the import of an npm project, on a change of the {@code package.json}
 * and for the modules owned by another build system (a Maven module with a frontend).
 * An importer only adds to the model: it never disables an extension or removes what the user or another importer
 * configured.
 *
 * @since 2026-10-31
 */
@ExtensionAPI(ComponentScope.APPLICATION)
public interface NpmImporter {
    boolean isApplicable(NpmPackage npmPackage);

    @RequiredReadAction
    void process(Module module, ModifiableRootModel model, NpmPackage npmPackage, VirtualFile packageRoot);

    /**
     * The directories generated by the framework (build output, caches) relative to the package directory, excluded
     * from the module: {@code dist}, {@code .nuxt}, {@code .angular}
     */
    default void collectExcludedDirectories(NpmPackage npmPackage, Consumer<String> relativePaths) {
    }
}
