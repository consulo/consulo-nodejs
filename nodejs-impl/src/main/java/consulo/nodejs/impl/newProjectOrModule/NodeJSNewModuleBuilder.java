package consulo.nodejs.impl.newProjectOrModule;

import consulo.annotation.access.RequiredReadAction;
import consulo.annotation.component.ExtensionImpl;
import consulo.application.AllIcons;
import consulo.content.bundle.Sdk;
import consulo.module.content.layer.ContentEntry;
import consulo.module.content.layer.ModifiableRootModel;
import consulo.module.creation.scratch.NewModuleBuilder;
import consulo.module.creation.scratch.NewModuleContext;
import consulo.module.creation.scratch.UnzipNewModuleBuilderProcessor;
import consulo.nodejs.impl.module.extension.NodeJSMutableModuleExtension;
import consulo.nodejs.newProjectOrModule.NodeJSNewModuleContext;
import consulo.nodejs.newProjectOrModule.NodeJSNewModuleSetupStep;
import consulo.nodejs.newProjectOrModule.NpxProjectGenerator;
import consulo.javascript.newProjectOrModule.WebNewModuleGroups;
import consulo.nodejs.icon.NodeJSApiIconGroup;
import consulo.nodejs.localize.NodeJSLocalize;
import consulo.localize.LocalizeValue;
import consulo.module.creation.scratch.NewModuleBuilderProcessor;
import consulo.module.creation.scratch.NewModuleContextGroup;
import consulo.virtualFileSystem.VirtualFile;
import consulo.ui.ex.wizard.WizardStep;

import jakarta.annotation.Nonnull;
import java.util.List;
import java.util.function.Consumer;

/**
 * @author VISTALL
 * @since 17.12.2015
 */
@ExtensionImpl
public class NodeJSNewModuleBuilder implements NewModuleBuilder
{
	@Override
	public void setupContext(@Nonnull NewModuleContext context)
	{
		NewModuleContext.Group group = context.createGroup("nodejs", "Node.js");

		group.add("Console Application", AllIcons.RunConfigurations.Application, new UnzipNewModuleBuilderProcessor<NodeJSNewModuleContext>("/moduleTemplates/#NodeJSHelloWorld.zip")
		{
			@Nonnull
			@Override
			public NodeJSNewModuleContext createContext(boolean isNewProject)
			{
				return new NodeJSNewModuleContext(isNewProject);
			}

			@Override
			public void buildSteps(@Nonnull Consumer<WizardStep<NodeJSNewModuleContext>> consumer, @Nonnull NodeJSNewModuleContext context)
			{
				consumer.accept(new NodeJSNewModuleSetupStep<>(context));
			}

			@RequiredReadAction
			@Override
			public void process(@Nonnull NodeJSNewModuleContext context, @Nonnull ContentEntry contentEntry, @Nonnull ModifiableRootModel modifiableRootModel)
			{
				unzip(modifiableRootModel);

				NodeJSMutableModuleExtension nodeJSModuleExtension = modifiableRootModel.getExtensionWithoutCheck(NodeJSMutableModuleExtension.class);
				assert nodeJSModuleExtension != null;

				nodeJSModuleExtension.setEnabled(true);

				Sdk sdk = context.getSdk();
				if(sdk != null)
				{
					nodeJSModuleExtension.getInheritableSdk().set(null, sdk);
					modifiableRootModel.addModuleExtensionSdkEntry(nodeJSModuleExtension);
				}
			}
		});

		// Node.js as a web tool: a frontend project built by Vite (the Node.js group above: Node.js as a backend runtime)
		NewModuleContextGroup webGroup = WebNewModuleGroups.getWebGroup(context).addGroup("nodejs", NodeJSLocalize.nodejsName(), NodeJSApiIconGroup.nodejs());
		webGroup.add(LocalizeValue.localizeTODO("Vite Application"), NodeJSApiIconGroup.nodejs(), new ViteNewModuleBuilderProcessor());
	}

	/**
	 * A project generated by {@code create-vite} with a template.
	 */
	private static class ViteNewModuleBuilderProcessor implements NewModuleBuilderProcessor<ViteNewModuleContext>
	{
		private static final String CREATE_VITE_PACKAGE = "create-vite@latest";

		@Nonnull
		@Override
		public ViteNewModuleContext createContext(boolean isNewProject)
		{
			return new ViteNewModuleContext(isNewProject);
		}

		@Override
		public void buildSteps(@Nonnull Consumer<WizardStep<ViteNewModuleContext>> consumer, @Nonnull ViteNewModuleContext context)
		{
			consumer.accept(new ViteNewModuleSetupStep(context));
		}

		@RequiredReadAction
		@Override
		public void process(@Nonnull ViteNewModuleContext context, @Nonnull ContentEntry contentEntry, @Nonnull ModifiableRootModel modifiableRootModel)
		{
			// a Vite application runs in a browser: Web, not Node.js - npm runs it with the chosen bundle
			context.setupWeb(modifiableRootModel);

			Sdk sdk = context.getSdk();
			VirtualFile directory = contentEntry.getFile();
			if(sdk != null && directory != null)
			{
				NpxProjectGenerator.generateWhenOpened(modifiableRootModel.getProject(), sdk, directory.toNioPath(), CREATE_VITE_PACKAGE,
						List.of("--template", context.getTemplate().getTemplate(), "--no-interactive"), "dev");
			}
		}
	}
}
